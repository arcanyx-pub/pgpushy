#[test]
fn rejects_statements_outside_the_allow_list() {
    for (sql, expected) in [
        ("CREATE VIEW v AS SELECT 1;", "CREATE VIEW"),
        ("INSERT INTO t VALUES (1);", "INSERT"),
        ("DROP TABLE t;", "DROP"),
        ("GRANT SELECT ON t TO joe;", "GRANT or REVOKE"),
        ("CREATE TYPE mood AS ENUM ('ok');", "CREATE TYPE"),
        ("CREATE SEQUENCE s;", "CREATE SEQUENCE"),
        ("ALTER TABLE t ADD COLUMN c int;", "ADD CONSTRAINT"),
        ("CREATE TABLE t (id int) INHERITS (parent);", "INHERITS"),
        ("CREATE INDEX CONCURRENTLY i ON t (c);", "CONCURRENTLY"),
    ] {
        let diagnostics = err(vec![file("bad.sql", sql)]);
        let diagnostic = only(&diagnostics, DiagnosticKind::UnsupportedStatement);
        assert!(
            diagnostic.message.contains(expected)
                || diagnostic
                    .help
                    .as_deref()
                    .is_some_and(|h| h.contains(expected)),
            "{sql:?} should mention {expected:?}, got: {diagnostic}",
        );
        assert_eq!(diagnostic.origins.len(), 1);
        assert_eq!(diagnostic.origins[0].file, "bad.sql");
    }
}

