/// The rule that keeps pgpushy from emptying a schema it was never told about:
/// a schema with no objects is not managed, even when it is the default.
#[test]
fn the_default_schema_is_not_managed_unless_it_holds_something() {
    let analysis = ok(vec![file(
        "billing.sql",
        "CREATE SCHEMA billing; CREATE TABLE billing.invoices (id int PRIMARY KEY);",
    )]);

    assert_eq!(analysis.managed_schemas, schemas(&["billing"]));
}

#[test]
fn a_declaration_rejects_a_schema_it_omits() {
    let options = Options {
        managed_schemas: Some(schemas(&["public"])),
        ..Options::default()
    };
    let diagnostics = err_with(
        vec![
            file("public.sql", "CREATE TABLE customers (id int PRIMARY KEY);"),
            file(
                "reporting/events.sql",
                "CREATE TABLE analytics.events (id int PRIMARY KEY);",
            ),
        ],
        &options,
    );

    let diagnostic = only(&diagnostics, DiagnosticKind::SchemaNotManaged);
    assert!(diagnostic.message.contains("analytics"), "{diagnostic}");
    assert_eq!(
        diagnostic.origins[0].file, "reporting/events.sql",
        "the diagnostic must name the file that enlisted the schema",
    );
}

/// A declared schema the tree never mentions is managed with an empty desired
/// state — the only way to say "reconcile this to empty", and destructive on
/// purpose.
#[test]
fn a_declaration_can_manage_a_schema_the_tree_never_mentions() {
    let options = Options {
        managed_schemas: Some(schemas(&["public", "legacy"])),
        ..Options::default()
    };
    let analysis = ok_with(
        vec![file(
            "t.sql",
            "CREATE TABLE customers (id int PRIMARY KEY);",
        )],
        &options,
    );

    assert_eq!(analysis.managed_schemas, schemas(&["legacy", "public"]));
    assert!(
        analysis
            .desired_state
            .contains("CREATE SCHEMA IF NOT EXISTS legacy;")
    );
}

#[test]
fn a_non_default_default_schema_assigns_unqualified_objects() {
    let options = Options {
        default_schema: schema("app"),
        ..Options::default()
    };
    let analysis = ok_with(
        vec![file(
            "t.sql",
            "CREATE TABLE customers (id int PRIMARY KEY);",
        )],
        &options,
    );

    assert_eq!(analysis.managed_schemas, schemas(&["app"]));
    assert!(
        analysis
            .desired_state
            .contains("CREATE TABLE app.customers")
    );
}

