/// The whole point, in one test: files in any order, foreign keys inline,
/// nothing qualified — and out comes a document that executes top to bottom.
#[test]
fn synthesizes_an_order_free_source_tree() {
    let analysis = ok(vec![
        // Deliberately the "wrong" order: the child table first, referencing a
        // parent defined in a file that sorts later. Raw pgschema fails on
        // this; pgpushy must not.
        file(
            "b_orders.sql",
            "CREATE TABLE orders (id int PRIMARY KEY, customer_id int NOT NULL REFERENCES customers(id));",
        ),
        file(
            "a_customers.sql",
            "CREATE TABLE customers (id int PRIMARY KEY, name text NOT NULL);",
        ),
    ]);

    assert_eq!(analysis.managed_schemas, schemas(&["public"]));
    assert_eq!(analysis.counts.tables, 2);
    assert_eq!(analysis.counts.foreign_keys, 1);
    assert!(analysis.cycles.is_empty());

    assert_eq!(
        analysis.desired_state,
        "-- Generated by pgpushy. Do not edit.\n\
         --\n\
         -- This is the desired state pgschema diffs against the target: every\n\
         -- managed schema's objects, schema-qualified, with foreign keys lifted\n\
         -- out of their tables so that no ordering among tables can matter.\n\
         \n\
         -- schemas\n\
         CREATE SCHEMA IF NOT EXISTS public;\n\
         \n\
         -- tables\n\
         CREATE TABLE public.customers (id int PRIMARY KEY, name text NOT NULL);\n\
         CREATE TABLE public.orders (id int PRIMARY KEY, customer_id int NOT NULL);\n\
         \n\
         -- foreign keys\n\
         ALTER TABLE public.orders ADD FOREIGN KEY (customer_id) REFERENCES public.customers (id);\n",
    );
}

/// Every category, in order, with each kind of statement the allow-list admits.
#[test]
fn emits_every_category_in_order() {
    let analysis = ok(vec![file(
        "all.sql",
        r#"
        COMMENT ON TABLE orders IS 'one per purchase';
        ALTER TABLE orders ADD CONSTRAINT orders_total_positive CHECK (total > 0);
        CREATE INDEX orders_customer_idx ON orders (customer_id);
        CREATE TABLE orders (id int PRIMARY KEY, customer_id int, total numeric);
        CREATE TABLE customers (id int PRIMARY KEY);
        ALTER TABLE orders ADD CONSTRAINT orders_customer_fk
            FOREIGN KEY (customer_id) REFERENCES customers(id);
        "#,
    )]);

    assert_eq!(
        body(&analysis),
        "CREATE SCHEMA IF NOT EXISTS public;\n\
         \n\
         -- tables\n\
         CREATE TABLE public.customers (id int PRIMARY KEY);\n\
         CREATE TABLE public.orders (id int PRIMARY KEY, customer_id int, total numeric);\n\
         \n\
         -- indexes and table constraints\n\
         CREATE INDEX orders_customer_idx ON public.orders USING btree (customer_id);\n\
         ALTER TABLE public.orders ADD CONSTRAINT orders_total_positive CHECK (total > 0);\n\
         \n\
         -- foreign keys\n\
         ALTER TABLE public.orders ADD CONSTRAINT orders_customer_fk FOREIGN KEY (customer_id) REFERENCES public.customers (id);\n\
         \n\
         -- comments\n\
         COMMENT ON TABLE public.orders IS 'one per purchase';",
    );
}

/// Spec §5.3: a foreign key the author did not name is emitted with no name,
/// so Postgres generates the same one it already generated on the target. A
/// name the author *did* write survives untouched.
#[test]
fn preserves_author_constraint_names_and_omits_generated_ones() {
    let analysis = ok(vec![file(
        "t.sql",
        "CREATE TABLE parent (id int PRIMARY KEY);
         CREATE TABLE a (pid int REFERENCES parent(id));
         CREATE TABLE b (pid int CONSTRAINT b_parent_fk REFERENCES parent(id));",
    )]);

    assert!(
        analysis
            .desired_state
            .contains("ALTER TABLE public.a ADD FOREIGN KEY (pid) REFERENCES public.parent (id);"),
        "unnamed constraint should stay unnamed:\n{}",
        analysis.desired_state
    );
    assert!(
        analysis.desired_state.contains(
            "ALTER TABLE public.b ADD CONSTRAINT b_parent_fk FOREIGN KEY (pid) REFERENCES public.parent (id);"
        ),
        "author's name should survive:\n{}",
        analysis.desired_state
    );
}

/// Spec §5.4: every identifier is qualified, including in the default schema,
/// because the combined document is run once per schema and an unqualified
/// object would be claimed by all of them.
#[test]
fn qualifies_every_identifier_including_the_default_schema() {
    let analysis = ok(vec![file(
        "t.sql",
        "CREATE SCHEMA billing;
         CREATE TABLE customers (id int PRIMARY KEY);
         CREATE TABLE billing.invoices (id int PRIMARY KEY, customer_id int REFERENCES customers(id));
         CREATE INDEX invoices_customer_idx ON billing.invoices (customer_id);",
    )]);

    for expected in [
        "CREATE TABLE public.customers",
        "CREATE TABLE billing.invoices",
        "ON billing.invoices",
        "REFERENCES public.customers",
    ] {
        assert!(
            analysis.desired_state.contains(expected),
            "expected {expected:?} in:\n{}",
            analysis.desired_state
        );
    }
}

/// A same-schema cycle has no valid inline ordering at all, which is the case
/// FK-lift exists for. It must produce no cross-schema edge and no complaint;
/// pgschema defers one constraint itself.
#[test]
fn same_schema_cycles_are_fine() {
    let analysis = ok(vec![file(
        "spouses.sql",
        "CREATE TABLE husband (id int PRIMARY KEY, wife_id int REFERENCES wife(id));
         CREATE TABLE wife (id int PRIMARY KEY, husband_id int REFERENCES husband(id));",
    )]);

    assert!(analysis.cycles.is_empty());
    assert_eq!(analysis.order, schemas(&["public"]));
    assert_eq!(analysis.counts.foreign_keys, 2);
}

