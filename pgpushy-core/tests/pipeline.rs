/// pgschema cannot reach inside a literal to strip a qualifier, so pgpushy
/// must be told which schema the name is in rather than guessing.
#[test]
fn rejects_a_bare_name_inside_a_string_literal() {
    for sql in [
        "CREATE TABLE t (id int DEFAULT nextval('s'));",
        "CREATE TABLE t (id int DEFAULT nextval('s'::regclass));",
        "CREATE TABLE t (a int DEFAULT (('x'::regtype)::oid)::int);",
    ] {
        let diagnostics = err(vec![file("t.sql", sql)]);
        let diagnostic = only(&diagnostics, DiagnosticKind::UnqualifiedNameLiteral);
        let rendered = diagnostic.to_string();
        assert!(
            rendered.contains("schema"),
            "{sql}\nshould say a schema is missing, got:\n{rendered}"
        );
    }
}

/// The qualified form is what `pg_dump` writes, and it is accepted as-is.
