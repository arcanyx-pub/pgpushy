#[test]
fn output_does_not_depend_on_file_order() {
    let contents = [
        (
            "z.sql",
            "CREATE TABLE zebra (id int PRIMARY KEY, a_id int REFERENCES aardvark(id));",
        ),
        ("a.sql", "CREATE TABLE aardvark (id int PRIMARY KEY);"),
        (
            "m.sql",
            "CREATE TABLE mongoose (id int PRIMARY KEY, z_id int REFERENCES zebra(id));",
        ),
    ];

    let forward = ok(contents.iter().map(|(p, c)| file(p, c)).collect());
    let reversed = ok(contents.iter().rev().map(|(p, c)| file(p, c)).collect());

    assert_eq!(forward.desired_state, reversed.desired_state);
    assert_eq!(forward.order, reversed.order);
}

#[test]
fn repeated_analysis_is_byte_identical() {
    let files = || {
        vec![file(
            "t.sql",
            "CREATE SCHEMA billing;
             CREATE TABLE billing.invoices (id int PRIMARY KEY, c int REFERENCES customers(id));
             CREATE TABLE customers (id int PRIMARY KEY);
             CREATE INDEX i ON customers (id);
             COMMENT ON TABLE customers IS 'people';",
        )]
    };

    assert_eq!(ok(files()).desired_state, ok(files()).desired_state);
}

