#[test]
fn rejects_a_duplicate_object_naming_both_definitions() {
    let diagnostics = err(vec![
        file(
            "services/a/orders.sql",
            "CREATE TABLE orders (id int PRIMARY KEY);",
        ),
        file(
            "services/b/orders.sql",
            "CREATE TABLE orders (id int PRIMARY KEY);",
        ),
    ]);

    let diagnostic = only(&diagnostics, DiagnosticKind::DuplicateObject);
    assert!(
        diagnostic.message.contains("table public.orders"),
        "{diagnostic}"
    );
    assert_eq!(
        diagnostic
            .origins
            .iter()
            .map(|o| o.file.as_str())
            .collect::<Vec<_>>(),
        vec!["services/a/orders.sql", "services/b/orders.sql"],
        "both definitions must be named",
    );
}

#[test]
fn rejects_a_foreign_key_to_a_table_no_file_defines() {
    let diagnostics = err(vec![file(
        "orders.sql",
        "CREATE TABLE orders (id int PRIMARY KEY, customer_id int REFERENCES customers(id));",
    )]);

    let diagnostic = only(&diagnostics, DiagnosticKind::UnresolvedReference);
    assert!(
        diagnostic.message.contains("public.customers"),
        "{diagnostic}"
    );
}

/// A foreign key into a schema the tree does not describe is the common cause,
/// and the help should say so rather than implying a missing file.
#[test]
fn explains_a_foreign_key_into_an_unmanaged_schema() {
    let diagnostics = err(vec![file(
        "orders.sql",
        "CREATE TABLE orders (id int PRIMARY KEY, user_id int REFERENCES auth.users(id));",
    )]);

    let diagnostic = only(&diagnostics, DiagnosticKind::UnresolvedReference);
    let help = diagnostic.help.as_deref().unwrap_or_default();
    assert!(
        help.contains("auth"),
        "help should name the schema: {diagnostic}"
    );
}

/// Spec §12.4: verified against Postgres 18, the numeric suffix Postgres adds
/// when two constraints compete for a name follows creation order — so these
/// two could swap names between the target and pgpushy's emission order.
#[test]
fn rejects_unnamed_foreign_keys_that_would_compete_for_one_name() {
    let diagnostics = err(vec![file(
        "dual.sql",
        "CREATE TABLE t1 (id int PRIMARY KEY);
         CREATE TABLE t2 (id int PRIMARY KEY);
         CREATE TABLE dual (ref_id int REFERENCES t1(id));
         ALTER TABLE dual ADD FOREIGN KEY (ref_id) REFERENCES t2(id);",
    )]);

    let diagnostic = only(&diagnostics, DiagnosticKind::CollidingUnnamedForeignKeys);
    assert!(
        diagnostic.message.contains("public.dual(ref_id)"),
        "{diagnostic}"
    );
    assert_eq!(diagnostic.origins.len(), 2);
}

/// The check is exact: naming either constraint resolves it, and two unnamed
/// foreign keys over *different* columns never collide.
#[test]
fn allows_unnamed_foreign_keys_that_cannot_collide() {
    ok(vec![file(
        "fine.sql",
        "CREATE TABLE t1 (id int PRIMARY KEY);
         CREATE TABLE t2 (id int PRIMARY KEY);
         -- different columns: different generated names
         CREATE TABLE a (x int REFERENCES t1(id), y int REFERENCES t2(id));
         -- same column, but one is named
         CREATE TABLE b (z int REFERENCES t1(id));
         ALTER TABLE b ADD CONSTRAINT b_z_t2_fk FOREIGN KEY (z) REFERENCES t2(id);",
    )]);
}

