/// A cycle is returned as data, not an error: `plan` shows the plans anyway,
/// because those plans are what the operator needs to break it.
#[test]
fn detects_a_cross_schema_cycle_without_failing_analysis() {
    let analysis = ok(vec![file(
        "t.sql",
        "CREATE SCHEMA billing;
         CREATE TABLE customers (id int PRIMARY KEY, account_id int REFERENCES billing.accounts(id));
         CREATE TABLE billing.accounts (id int PRIMARY KEY, owner_id int REFERENCES customers(id));",
    )]);

    assert_eq!(analysis.cycles.len(), 1);
    assert_eq!(analysis.cycles[0].schemas, schemas(&["billing", "public"]));
    assert_eq!(
        analysis.order.len(),
        2,
        "every schema still appears in the order"
    );

    let diagnostic = &analysis.cycle_diagnostics()[0];
    assert_eq!(diagnostic.kind, DiagnosticKind::CrossSchemaForeignKeyCycle);
    assert!(diagnostic.message.contains("billing"), "{diagnostic}");
    assert!(diagnostic.message.contains("public"), "{diagnostic}");
    assert_eq!(
        diagnostic.origins.len(),
        2,
        "both constraints should be named"
    );
}

#[test]
