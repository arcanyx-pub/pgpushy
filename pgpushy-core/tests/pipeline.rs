#[test]
fn orders_referenced_schemas_first() {
    let analysis = ok(vec![file(
        "t.sql",
        "CREATE SCHEMA billing;
         CREATE SCHEMA reporting;
         CREATE TABLE customers (id int PRIMARY KEY);
         CREATE TABLE billing.invoices (id int PRIMARY KEY, c int REFERENCES customers(id));
         CREATE TABLE reporting.summaries (id int PRIMARY KEY, i int REFERENCES billing.invoices(id));",
    )]);

    assert!(analysis.cycles.is_empty());
    assert_eq!(analysis.order, schemas(&["public", "billing", "reporting"]));
}

/// Schemas with no cross-schema foreign keys still appear, in a stable order.
#[test]
fn independent_schemas_are_ordered_by_name() {
    let analysis = ok(vec![file(
        "t.sql",
        "CREATE SCHEMA b; CREATE SCHEMA a; CREATE SCHEMA c;
         CREATE TABLE a.t (id int); CREATE TABLE b.t (id int); CREATE TABLE c.t (id int);",
    )]);

    assert_eq!(analysis.order, schemas(&["a", "b", "c"]));
}

/// A cycle is returned as data, not an error: `plan` shows the plans anyway,
/// because those plans are what the operator needs to break it.
#[test]
fn detects_a_cross_schema_cycle_without_failing_analysis() {
    let analysis = ok(vec![file(
        "t.sql",
        "CREATE SCHEMA billing;
         CREATE TABLE customers (id int PRIMARY KEY, account_id int REFERENCES billing.accounts(id));
         CREATE TABLE billing.accounts (id int PRIMARY KEY, owner_id int REFERENCES customers(id));",
    )]);

    assert_eq!(analysis.cycles.len(), 1);
    assert_eq!(analysis.cycles[0].schemas, schemas(&["billing", "public"]));
    assert_eq!(
        analysis.order.len(),
        2,
        "every schema still appears in the order"
    );

    let diagnostic = &analysis.cycle_diagnostics()[0];
    assert_eq!(diagnostic.kind, DiagnosticKind::CrossSchemaForeignKeyCycle);
    assert!(diagnostic.message.contains("billing"), "{diagnostic}");
    assert!(diagnostic.message.contains("public"), "{diagnostic}");
    assert_eq!(
        diagnostic.origins.len(),
        2,
        "both constraints should be named"
    );
}

#[test]
fn a_three_schema_cycle_names_all_three() {
    let analysis = ok(vec![file(
        "t.sql",
        "CREATE SCHEMA b; CREATE SCHEMA c;
         CREATE TABLE a (id int PRIMARY KEY, r int REFERENCES b.b(id));
         CREATE TABLE b.b (id int PRIMARY KEY, r int REFERENCES c.c(id));
         CREATE TABLE c.c (id int PRIMARY KEY, r int REFERENCES a(id));",
    )]);

    assert_eq!(analysis.cycles.len(), 1);
    assert_eq!(analysis.cycles[0].schemas, schemas(&["b", "c", "public"]));
}
