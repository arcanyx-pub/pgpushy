//! End-to-end tests for the offline pipeline.
//!
//! `pgpushy-core` takes `(path, contents)` pairs rather than reading the
//! filesystem, so every one of these is a string-literal test with no fixture
//! directory to keep in sync — which is the main reason discovery lives in the
//! binary and everything downstream of it does not.

use pgpushy_core::{
    Analysis, AnalysisError, Diagnostic, DiagnosticKind, Options, SchemaName, SourceFile, analyze,
};

fn file(path: &str, contents: &str) -> SourceFile {
    SourceFile {
        path: path.to_owned(),
        contents: contents.to_owned(),
    }
}

fn analyze_with(files: &[SourceFile], options: &Options) -> Result<Analysis, AnalysisError> {
    analyze(files, options)
}

fn ok(files: Vec<SourceFile>) -> Analysis {
    ok_with(files, &Options::default())
}

fn ok_with(files: Vec<SourceFile>, options: &Options) -> Analysis {
    match analyze_with(&files, options) {
        Ok(analysis) => analysis,
        Err(err) => panic!("expected success, got:\n{}", render(&err)),
    }
}

fn err(files: Vec<SourceFile>) -> Vec<Diagnostic> {
    err_with(files, &Options::default())
}

fn err_with(files: Vec<SourceFile>, options: &Options) -> Vec<Diagnostic> {
    match analyze_with(&files, options) {
        Ok(_) => panic!("expected failure, got success"),
        Err(AnalysisError::Source(diagnostics)) => diagnostics,
        Err(other) => panic!("expected source diagnostics, got: {other}"),
    }
}

fn render(err: &AnalysisError) -> String {
    match err {
        AnalysisError::Source(diagnostics) => diagnostics
            .iter()
            .map(ToString::to_string)
            .collect::<Vec<_>>()
            .join("\n"),
        other => other.to_string(),
    }
}

fn only(diagnostics: &[Diagnostic], kind: DiagnosticKind) -> &Diagnostic {
    assert_eq!(
        diagnostics.iter().map(|d| d.kind).collect::<Vec<_>>(),
        vec![kind],
        "unexpected diagnostics:\n{}",
        diagnostics
            .iter()
            .map(ToString::to_string)
            .collect::<Vec<_>>()
            .join("\n"),
    );
    &diagnostics[0]
}

fn schema(name: &str) -> SchemaName {
    SchemaName::new(name)
}

fn schemas(names: &[&str]) -> Vec<SchemaName> {
    names.iter().map(|n| schema(n)).collect()
}

/// The body of a synthesized document, minus the fixed header.
fn body(analysis: &Analysis) -> String {
    analysis
        .desired_state
        .lines()
        .skip_while(|line| line.starts_with("--") || line.is_empty())
        .collect::<Vec<_>>()
        .join("\n")
}

