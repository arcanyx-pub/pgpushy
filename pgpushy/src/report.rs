/// `plan` lists the seed files and executes none of them (spec §8.8).
pub fn seeds_planned(seeds: &Seeds) {
    println!(
        "\n  {} would be applied after the schemas; plan executes none:",
        plural(seeds.files.len(), "seed file"),
    );
    for file in &seeds.files {
        println!(
            "    {}  {}",
            file.path,
            plural(file.statements.len(), "statement"),
        );
    }
}

pub fn seed_heading(path: &str) {
    println!("\n\u{2500}\u{2500} seed {path} \u{2500}\u{2500}");
}

/// A committed seed file, with its first-pass affected count — the rows that
/// landed or were corrected. The probe pass affected none, by construction.
pub fn seed_applied(path: &str, rows: u64, per_statement: &[(u32, u64)]) {
    println!(
        "  {path}: {rows} row{} affected; probe passed",
        s(usize::try_from(rows).unwrap_or(2)),
    );
    // One statement's count is the file's count; several are worth itemizing
    // (spec §8.8 step 2).
    if per_statement.len() > 1 {
        for (line, count) in per_statement {
            println!(
                "    line {line}: {count} row{}",
                s(usize::try_from(*count).unwrap_or(2)),
            );
        }
    }
}

/// A statement failed outright; the file's transaction rolls back.
pub fn seed_statement_error(path: &str, origin: &Origin, err: &postgres::Error) {
    eprintln!(
        "\nerror: seed {path} failed\n  at {origin}\n  {err}\n\n  The file's \
         transaction was rolled back; nothing from it landed."
    );
}

/// The probe caught a non-convergent seed (spec §8.8, §11.1).
pub fn seed_probe_failure(path: &str, origin: &Origin, affected: u64) {
    eprintln!(
        "\nerror: seed {path} does not converge\n  at {origin}\n  the second pass \
         affected {affected} row{} where it must affect none\n\n  A seed must leave \
         nothing to do when re-run (spec §11.1): a volatile expression, or an update \
         that keeps rewriting rows, cannot be a seed. The file's transaction was \
         rolled back; nothing from it landed.",
        s(usize::try_from(affected).unwrap_or(2)),
    );
}

/// Where the seed pass stopped (spec §9).
pub fn seeds_partial(applied: &[String], failed: &str, unattempted: &[&str]) {
    eprintln!(
        "\n  seed files applied and committed: {}",
        if applied.is_empty() {
            "none".to_owned()
        } else {
            applied.join(", ")
        },
    );
    eprintln!("  failed (rolled back): {failed}");
    if !unattempted.is_empty() {
        eprintln!("  not attempted: {}", unattempted.join(", "));
    }
    eprintln!("\n  Committed seed files are not rolled back (spec §11.2).");
}

