use std::path::Path;

/// What discovery found, before anything is parsed.
///
/// Printed early and unconditionally: when an exclude pattern is too broad, or
/// a source root points somewhere unexpected, the file count is the thing that
/// gives it away.
pub fn discovery(root: &Path, discovered: &Discovered) {
    let total: usize = discovered.excluded.iter().map(|(_, n)| n).sum();
    let plural = if discovered.files.len() == 1 { "" } else { "s" };

    if total == 0 {
        println!(
            "  {} ({} file{plural})",
            root.display(),
            discovered.files.len()
        );
    } else {
        println!(
            "  {} ({} file{plural}, {total} excluded)",
            root.display(),
            discovered.files.len(),
        );
        for (pattern, count) in &discovered.excluded {
            if *count > 0 {
                println!("    excluded by {pattern:?}: {count}");
            }
        }
    }

    if discovered.generated > 0 {
        println!(
            "    skipped {} previously generated by pgpushy",
            discovered.generated,
        );
    }

    if discovered.skipped_seed_root > 0 {
        let n = discovered.skipped_seed_root;
        println!(
            "    excluded {n} seed file{} under the seed root (not desired state)",
            if n == 1 { "" } else { "s" },
        );
    }
}

/// The managed-schema set and what the tree contains.
pub fn summary(settings: &Settings, analysis: &Analysis) {
    let counts = &analysis.counts;
    let mut parts = vec![format!("{} table{}", counts.tables, s(counts.tables))];
    if counts.foreign_keys > 0 {
        parts.push(format!(
            "{} foreign key{}",
            counts.foreign_keys,
            s(counts.foreign_keys)
        ));
    }
    if counts.indexes > 0 {
        parts.push(format!("{} index{}", counts.indexes, es(counts.indexes)));
    }
    if counts.types > 0 {
        parts.push(format!(
            "{} type{} and sequence{}",
            counts.types,
            s(counts.types),
            s(counts.types)
        ));
    }
    if counts.comments > 0 {
        parts.push(format!("{} comment{}", counts.comments, s(counts.comments)));
    }
    println!("  {}", parts.join(", "));

    let declared = if settings.managed_schemas.is_none() {
        ""
    } else {
        " (declared)"
    };
    if !analysis.managed_schemas.is_empty() {
        println!(
            "\n  managed schemas{declared}: {}",
            analysis
                .managed_schemas
                .iter()
                .map(|s| s.as_str().to_owned())
                .collect::<Vec<_>>()
                .join(", "),
        );
    }

    // A managed schema with nothing in it reconciles the target's copy to
    // empty. That is the only way to say so, and it is destructive, so it is
    // never left implicit.
    let empty: Vec<_> = analysis
        .managed_schemas
        .iter()
        .filter(|schema| !mentions(analysis, schema))
        .map(|s| s.as_str())
        .collect();
    if !empty.is_empty() {
        println!(
            "  WARNING: no source file describes {}; applying would plan to drop \
             everything the target holds there",
            empty.join(", "),
        );
    }

    if analysis.counts.seed_files > 0 {
        println!(
            "  {} seed statement{} across {}",
            analysis.counts.seed_statements,
            s(analysis.counts.seed_statements),
            plural(analysis.counts.seed_files, "seed file"),
        );
    }
    // The per-file probe cannot see two files converging against each other
    // (spec §4.6, §12.11), so the statically visible shape is warned about.
    for collision in &analysis.seeds.do_update_collisions {
        println!(
            "  WARNING: two DO UPDATE seeds share a conflict target on {} ({}); \
             each converges alone while together they rewrite the row on every apply",
            collision.table,
            collision
                .origins
                .iter()
                .map(|origin| origin.to_string())
                .collect::<Vec<_>>()
                .join(", "),
        );
    }
}

/// The all-clear, plus the order the schemas would be applied in.
pub fn checks_passed(analysis: &Analysis) {
    println!("\n  ok  no duplicate objects");
    println!("  ok  all foreign key referents resolvable");
    println!("  ok  no cross-schema foreign key cycles");
    println!("  ok  no unsupported statements");
    if analysis.counts.seed_files > 0 {
        println!("  ok  seed statements are idempotent by construction");
    }

    if analysis.order.len() > 1 {
        println!(
            "\n  schema apply order: {}",
            analysis
                .order
                .iter()
                .map(|s| s.as_str().to_owned())
                .collect::<Vec<_>>()
                .join(", "),
        );
    }
}

/// The documents `--out` just wrote (spec §8.7).
pub fn wrote(dir: &Path, written: &[std::path::PathBuf]) {
    println!(
        "\n  wrote {} into {}",
        plural(written.len(), "document"),
        dir.display()
    );
    for path in written {
        if let Some(name) = path.file_name() {
            println!("    {}", name.to_string_lossy());
        }
    }
}

fn plural(n: usize, word: &str) -> String {
    format!("{n} {word}{}", s(n))
}

/// Print every diagnostic, to stderr.
pub fn diagnostics(diagnostics: &[Diagnostic]) {
    eprintln!();
    for diagnostic in diagnostics {
        eprintln!("error: {}", diagnostic.message);
        for origin in &diagnostic.origins {
            eprintln!("  at {origin}");
        }
        if let Some(help) = &diagnostic.help {
            eprintln!("  help: {help}");
        }
        eprintln!();
    }

    let count = diagnostics.len();
    eprintln!("{count} problem{} found in the source tree", s(count));
}

/// Whether any object was assigned to this schema.
fn mentions(analysis: &Analysis, schema: &pgpushy_core::SchemaName) -> bool {
    !analysis.empty_schemas.contains(schema)
}

fn s(n: usize) -> &'static str {
    if n == 1 { "" } else { "s" }
}

fn es(n: usize) -> &'static str {
    if n == 1 { "" } else { "es" }
}

/// Which pgschema is about to be run.
///
/// Printed because the binary in use determines what the plans mean, and a
/// `PATH` lookup can quietly find a different one than the operator expects.
pub fn pgschema(binary: &PgschemaBin) {
    let version = binary
        .version
        .as_ref()
        .map(|v| v.to_string())
        .unwrap_or_else(|| "unknown version".to_owned());
    println!("\n  pgschema {version} ({})", binary.path.display());
}

/// Which database pgpushy actually reached (spec §6.3).
/// Where the comparison model is built, when it is not the embedded default.
